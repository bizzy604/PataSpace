#!/usr/bin/env bash
# Purpose: Behavioural proof that a full rebuild cannot wipe the database.
# Why important: The gate tests assert the *structure* that prevents data loss
#   (external volumes, no destructive flags). Structure can be right and the
#   behaviour still wrong. This runs real Docker against the real compose file
#   and checks that the bytes actually survive — including a counter-experiment
#   that shows the OLD configuration genuinely did destroy them, so a pass here
#   means something.
# Used by: `pnpm eval:deploy`. Nightly and before any change to the deploy path.
#
#   bash infra/deploy/tests/persistence.eval.sh          # all scenarios
#   bash infra/deploy/tests/persistence.eval.sh --keep   # leave the stack for inspection
#
# Cost: ~90s, no image builds (only the postgres service is started), no network
# beyond pulling postgres:16 and alpine:3 if they are not cached.
#
# Isolation: everything created here is prefixed `pataspace-eval` /
# `pataspace_eval_`. Production volumes are never named, never mounted, and the
# cleanup trap refuses to remove anything outside that prefix.
#
# Exit codes: 0 every scenario passed, 1 a scenario failed, 2 prerequisites missing.

set -Eeuo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEPLOY_DIR="$(cd "$HERE/.." && pwd)"
REPO_ROOT="$(cd "$DEPLOY_DIR/../.." && pwd)"

# Docker Desktop on Windows cannot resolve an MSYS path like /c/Users/... — it
# reads it as C:\c\Users\... and fails. cygpath -m produces C:/Users/..., which
# both Docker and MSYS bash accept. On Linux (the VPS) this is the identity.
# Note: do NOT set MSYS_NO_PATHCONV globally instead; that leaves host paths
# unconverted and breaks -f/--project-directory in exactly this way.
hostpath() {
  if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else printf '%s' "$1"; fi
}

COMPOSE_DIR="$(hostpath "$REPO_ROOT/infra/docker")"
COMPOSE_FILE="$COMPOSE_DIR/docker-compose.vps.yml"

# --- Isolation namespace. Nothing outside this prefix is ever touched. --------
readonly EVAL_PREFIX="pataspace_eval"
readonly EVAL_PROJECT="pataspace-eval"
readonly PG_VOLUME="${EVAL_PREFIX}_postgres_data"
readonly REDIS_VOLUME_EVAL="${EVAL_PREFIX}_redis_data"
readonly MARKER="pataspace-eval-marker-do-not-delete"

KEEP=0
for arg in "$@"; do
  case "$arg" in
    --keep) KEEP=1 ;;
    -h|--help) sed -n '2,22p' "$0"; exit 0 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

# --- Output -------------------------------------------------------------------
if [ -t 2 ]; then C_OK=$'\033[32m'; C_NO=$'\033[31m'; C_DIM=$'\033[2m'; C_OFF=$'\033[0m'
else C_OK=""; C_NO=""; C_DIM=""; C_OFF=""; fi

PASSED=0; FAILED=0; CURRENT=""
say()  { printf '%s\n' "$*" >&2; }
step() { printf '%s   · %s%s\n' "$C_DIM" "$*" "$C_OFF" >&2; }
scenario() { CURRENT="$1"; printf '\n%s\n' "$1" >&2; }
pass() { PASSED=$((PASSED+1)); printf '%s  PASS%s  %s\n' "$C_OK" "$C_OFF" "${1:-$CURRENT}" >&2; }
fail() { FAILED=$((FAILED+1)); printf '%s  FAIL%s  %s\n' "$C_NO" "$C_OFF" "${1:-$CURRENT}" >&2; }
abort() { printf '%s  ABORT%s %s\n' "$C_NO" "$C_OFF" "$*" >&2; exit 2; }

# --- Prerequisites ------------------------------------------------------------
command -v docker >/dev/null 2>&1 || abort "docker not on PATH"
docker info >/dev/null 2>&1 || abort "Docker daemon unreachable"
[ -f "$COMPOSE_FILE" ] || abort "missing $COMPOSE_FILE"

# The compose file's services declare `env_file: [.env]`, and Compose refuses to
# load the document without it. On the VPS a real .env exists and is used as-is;
# locally we create a throwaway one and remove it again. Never overwritten.
CREATED_ENV=0
if [ ! -f "$COMPOSE_DIR/.env" ]; then
  step "no infra/docker/.env — writing a throwaway one for this run"
  cat > "$COMPOSE_DIR/.env" <<'ENV'
# Generated by persistence.eval.sh. Throwaway values, removed when the eval ends.
POSTGRES_PASSWORD=eval-only-not-a-secret
PATA_DB_APP_PASSWORD=eval-only-not-a-secret
PATA_DB_MIGRATOR_PASSWORD=eval-only-not-a-secret
REDIS_PASSWORD=eval-only-not-a-secret
AUTH_SECRET=eval-only-not-a-secret-eval-only-not-a-secret
AUTH_URL=http://127.0.0.1:3003
ENV
  CREATED_ENV=1
fi

TMP_DIR="$(hostpath "$(mktemp -d)")"

# --- Cleanup ------------------------------------------------------------------
# Refuses to remove anything whose name does not start with the eval prefix, so
# a copy/paste error can never reach a production volume.
remove_eval_volume() {
  local vol="$1"
  case "$vol" in
    "${EVAL_PREFIX}"_*) ;;
    *) say "REFUSING to remove '$vol' — outside the eval namespace"; return 1 ;;
  esac
  docker volume rm "$vol" >/dev/null 2>&1 || true
}

cleanup() {
  local code=$?
  set +e
  if [ "$KEEP" = 1 ]; then
    say ""
    say "--keep: leaving the eval stack up. Inspect with:"
    say "  docker compose -p $EVAL_PROJECT -f $COMPOSE_FILE ps"
    say "  docker volume ls | grep $EVAL_PREFIX"
    say "Tear it down with: bash $0 --cleanup-only  (or docker volume rm $PG_VOLUME)"
  else
    step "cleaning up the eval namespace"
    ev down --remove-orphans >/dev/null 2>&1
    docker compose -p "${EVAL_PROJECT}-inline" -f "$TMP_DIR/inline.yml" down -v --remove-orphans >/dev/null 2>&1
    docker compose -p "${EVAL_PROJECT}-elsewhere" -f "$TMP_DIR/elsewhere/docker-compose.vps.yml" down --remove-orphans >/dev/null 2>&1
    remove_eval_volume "$PG_VOLUME"
    remove_eval_volume "$REDIS_VOLUME_EVAL"
  fi
  [ "$CREATED_ENV" = 1 ] && rm -f "$COMPOSE_DIR/.env"
  rm -rf "$TMP_DIR"
  exit "$code"
}
trap cleanup EXIT

# --- Helpers ------------------------------------------------------------------

# The eval stack: the real compose file, isolated project name and volumes.
ev() {
  POSTGRES_VOLUME="$PG_VOLUME" REDIS_VOLUME="$REDIS_VOLUME_EVAL" \
    docker compose -p "$EVAL_PROJECT" -f "$COMPOSE_FILE" --project-directory "$COMPOSE_DIR" "$@"
}

wait_for_pg() {
  local project="${1:-$EVAL_PROJECT}" file="${2:-$COMPOSE_FILE}" i
  for i in $(seq 1 60); do
    if POSTGRES_VOLUME="$PG_VOLUME" REDIS_VOLUME="$REDIS_VOLUME_EVAL" \
       docker compose -p "$project" -f "$file" --project-directory "$(dirname "$file")" \
       exec -T postgres pg_isready -U postgres -d pataspace >/dev/null 2>&1; then
      return 0
    fi
    sleep 1
  done
  return 1
}

psql_in() { # psql_in <project> <compose-file> <sql>  — reads a single value
  POSTGRES_VOLUME="$PG_VOLUME" REDIS_VOLUME="$REDIS_VOLUME_EVAL" \
    docker compose -p "$1" -f "$2" --project-directory "$(dirname "$2")" \
    exec -T postgres psql -U postgres -d pataspace -tAq -c "$3" 2>/dev/null | tr -d ' \r\n'
}

# psql_in drops stderr, so a statement that fails looks identical to one that
# returned nothing. Anything run for effect goes through here instead, where a
# failure is loud — a silently-failed DDL would make a scenario pass for the
# wrong reason.
psql_exec() { # psql_exec <project> <compose-file> <sql>
  local out
  if ! out="$(POSTGRES_VOLUME="$PG_VOLUME" REDIS_VOLUME="$REDIS_VOLUME_EVAL" \
       docker compose -p "$1" -f "$2" --project-directory "$(dirname "$2")" \
       exec -T postgres psql -U postgres -d pataspace -v ON_ERROR_STOP=1 -q -c "$3" 2>&1)"; then
    say "      psql: $(printf '%s' "$out" | head -3 | tr '\n' ' ')"
    return 1
  fi
}

seed_marker() { psql_exec "$1" "$2" \
  "CREATE TABLE IF NOT EXISTS pata_eval_marker(id int primary key, note text);
   INSERT INTO pata_eval_marker VALUES (1,'$MARKER') ON CONFLICT (id) DO NOTHING;"; }

# Two statements, deliberately. A single `SELECT ... FROM pata_eval_marker`
# fails at PARSE time when the table is gone — psql writes to stderr, psql_in
# swallows it, and the caller sees "" rather than ABSENT. Checking existence
# first is what makes "table dropped" and "row missing" both report ABSENT.
read_marker() { # read_marker <project> <compose-file>
  if [ "$(psql_in "$1" "$2" "SELECT to_regclass('public.pata_eval_marker') IS NOT NULL;")" != "t" ]; then
    printf 'ABSENT'; return 0
  fi
  local note; note="$(psql_in "$1" "$2" "SELECT note FROM pata_eval_marker WHERE id=1;")"
  printf '%s' "${note:-ABSENT}"
}

say "PataSpace data-persistence eval"
say "${C_DIM}  compose : $COMPOSE_FILE"
say "  project : $EVAL_PROJECT"
say "  volume  : $PG_VOLUME${C_OFF}"

# Start from a clean slate so a leftover volume from a previous run cannot make
# a scenario pass for the wrong reason.
remove_eval_volume "$PG_VOLUME" || true
remove_eval_volume "$REDIS_VOLUME_EVAL" || true
docker volume create "$PG_VOLUME" >/dev/null
docker volume create "$REDIS_VOLUME_EVAL" >/dev/null

# =============================================================================
scenario "1. 'docker compose down -v' cannot delete the external volume"
# =============================================================================
step "starting postgres"
# Keep compose's own error text: a silenced failure here is what turned a path
# bug into the useless message "postgres never became ready".
if ! ev up -d postgres >"$TMP_DIR/up.log" 2>&1; then
  say ""
  sed 's/^/      /' "$TMP_DIR/up.log" >&2
  abort "docker compose could not start postgres (output above)"
fi
wait_for_pg || {
  ev logs --tail=30 postgres 2>&1 | sed 's/^/      /' >&2 || true
  abort "postgres never became ready (logs above)"
}

step "writing marker row"
seed_marker "$EVAL_PROJECT" "$COMPOSE_FILE"
[ "$(read_marker "$EVAL_PROJECT" "$COMPOSE_FILE")" = "$MARKER" ] || abort "could not seed the marker row"

CREATED_AT_BEFORE="$(docker volume inspect "$PG_VOLUME" --format '{{.CreatedAt}}')"

step "running the command that used to wipe the database: down -v"
# Deliberate: this is the destructive command, aimed at the eval namespace only.
ev down -v --remove-orphans >/dev/null 2>&1 || true

if docker volume inspect "$PG_VOLUME" >/dev/null 2>&1; then
  step "volume survived; restarting to read the data back"
  ev up -d postgres >/dev/null 2>&1
  if wait_for_pg && [ "$(read_marker "$EVAL_PROJECT" "$COMPOSE_FILE")" = "$MARKER" ]; then
    CREATED_AT_AFTER="$(docker volume inspect "$PG_VOLUME" --format '{{.CreatedAt}}')"
    if [ "$CREATED_AT_BEFORE" = "$CREATED_AT_AFTER" ]; then
      pass "marker row survived 'down -v'; volume was never recreated ($CREATED_AT_AFTER)"
    else
      fail "data is present but the volume was recreated ($CREATED_AT_BEFORE -> $CREATED_AT_AFTER)"
    fi
  else
    fail "volume survived but the marker row did not — the data directory was emptied"
  fi
else
  fail "'down -v' DELETED $PG_VOLUME — the external declaration is not in effect"
fi

# =============================================================================
scenario "2. counter-experiment: the OLD inline config really did destroy data"
# =============================================================================
# Without this, scenario 1 proves nothing: a volume that was never deletable in
# the first place would pass it. This shows Docker deletes an inline volume under
# exactly the same command, so scenario 1 is measuring a real difference.
cat > "$TMP_DIR/inline.yml" <<YAML
name: ${EVAL_PROJECT}-inline
services:
  postgres:
    image: postgres:16
    environment:
      POSTGRES_DB: pataspace
      POSTGRES_USER: postgres
      POSTGRES_PASSWORD: eval-only-not-a-secret
    volumes:
      - postgres_data:/var/lib/postgresql/data
volumes:
  postgres_data:
YAML

step "starting a stack with the pre-fix inline volume"
docker compose -p "${EVAL_PROJECT}-inline" -f "$TMP_DIR/inline.yml" up -d postgres >/dev/null 2>&1
wait_for_pg "${EVAL_PROJECT}-inline" "$TMP_DIR/inline.yml" || abort "inline postgres never became ready"

seed_marker "${EVAL_PROJECT}-inline" "$TMP_DIR/inline.yml"
[ "$(read_marker "${EVAL_PROJECT}-inline" "$TMP_DIR/inline.yml")" = "$MARKER" ] \
  || abort "could not seed the inline stack"

INLINE_VOL="$(docker compose -p "${EVAL_PROJECT}-inline" -f "$TMP_DIR/inline.yml" \
  config --format json 2>/dev/null | grep -o "${EVAL_PROJECT}-inline_postgres_data" | head -1 || true)"
INLINE_VOL="${INLINE_VOL:-${EVAL_PROJECT}-inline_postgres_data}"

step "same command, inline volume: down -v"
docker compose -p "${EVAL_PROJECT}-inline" -f "$TMP_DIR/inline.yml" down -v --remove-orphans >/dev/null 2>&1 || true

if docker volume inspect "$INLINE_VOL" >/dev/null 2>&1; then
  fail "the inline volume ALSO survived — this Docker version does not delete it, so scenario 1 proves nothing on this host"
else
  pass "inline volume was destroyed by the same command — the external declaration is what saves the data"
fi

# =============================================================================
scenario "3. rebuilding from a different directory attaches the SAME database"
# =============================================================================
# The silent-wipe path that has nothing to do with -v: an inline volume is
# namespaced <project>_<key>, so a re-clone into a new directory used to come up
# with an empty database. The pinned `name:` is what prevents it.
mkdir -p "$TMP_DIR/elsewhere"
cp "$COMPOSE_FILE" "$TMP_DIR/elsewhere/docker-compose.vps.yml"
[ -f "$COMPOSE_DIR/.env" ] && cp "$COMPOSE_DIR/.env" "$TMP_DIR/elsewhere/.env"
mkdir -p "$TMP_DIR/elsewhere/../../apps/api/prisma/bootstrap" 2>/dev/null || true
cp -r "$REPO_ROOT/apps/api/prisma/bootstrap" "$TMP_DIR/elsewhere/bootstrap" 2>/dev/null || true
# Point the bind mount at the copied bootstrap dir so the path resolves.
sed -i.bak 's#\.\./\.\./apps/api/prisma/bootstrap#./bootstrap#' "$TMP_DIR/elsewhere/docker-compose.vps.yml" 2>/dev/null \
  || sed -i 's#\.\./\.\./apps/api/prisma/bootstrap#./bootstrap#' "$TMP_DIR/elsewhere/docker-compose.vps.yml"

step "bringing the stack up from $TMP_DIR/elsewhere under a different project name"
ev stop postgres >/dev/null 2>&1 || true
POSTGRES_VOLUME="$PG_VOLUME" REDIS_VOLUME="$REDIS_VOLUME_EVAL" \
  docker compose -p "${EVAL_PROJECT}-elsewhere" -f "$TMP_DIR/elsewhere/docker-compose.vps.yml" \
  --project-directory "$TMP_DIR/elsewhere" up -d postgres >/dev/null 2>&1

if wait_for_pg "${EVAL_PROJECT}-elsewhere" "$TMP_DIR/elsewhere/docker-compose.vps.yml" \
   && [ "$(read_marker "${EVAL_PROJECT}-elsewhere" "$TMP_DIR/elsewhere/docker-compose.vps.yml")" = "$MARKER" ]; then
  pass "a different directory and project name still attached the same database"
else
  fail "the stack came up with an empty database — the pinned volume name is not being honoured"
fi

POSTGRES_VOLUME="$PG_VOLUME" REDIS_VOLUME="$REDIS_VOLUME_EVAL" \
  docker compose -p "${EVAL_PROJECT}-elsewhere" -f "$TMP_DIR/elsewhere/docker-compose.vps.yml" \
  --project-directory "$TMP_DIR/elsewhere" down --remove-orphans >/dev/null 2>&1 || true

# =============================================================================
scenario "4. dc_safe refuses a volume-destroying command at runtime"
# =============================================================================
# The gate proves no script *contains* one. This proves the guard fires even if
# somebody types one by hand while sourcing lib.sh.
GUARD_OUT="$(
  COMPOSE_FILE="$COMPOSE_FILE" bash -c '
    set +e
    . "'"$DEPLOY_DIR"'/lib.sh"
    dc_safe down -v 2>&1
    echo "EXIT:$?"
  ' 2>&1 || true
)"

if printf '%s' "$GUARD_OUT" | grep -q 'refusing compose command' \
   && ! printf '%s' "$GUARD_OUT" | grep -q 'EXIT:0'; then
  pass "dc_safe rejected 'down -v' and exited non-zero"
else
  fail "dc_safe did NOT reject 'down -v' (output: $(printf '%s' "$GUARD_OUT" | head -3 | tr '\n' ' '))"
fi

# =============================================================================
scenario "5. the pre-deploy backup is restorable"
# =============================================================================
# A backup nobody has restored is a hope, not a backup. Dump, destroy the table,
# restore, and read the marker back.
step "restarting the eval stack"
ev up -d postgres >/dev/null 2>&1
wait_for_pg || abort "postgres never came back"

DUMP="$TMP_DIR/eval-backup.sql.gz"
step "dumping to $DUMP"
if ev exec -T postgres pg_dump -U postgres -d pataspace --clean --if-exists 2>/dev/null \
     | gzip -9 > "$DUMP" && gzip -t "$DUMP" 2>/dev/null; then

  step "dropping the marker table to simulate the loss"
  psql_in "$EVAL_PROJECT" "$COMPOSE_FILE" "DROP TABLE pata_eval_marker;" >/dev/null
  [ "$(read_marker "$EVAL_PROJECT" "$COMPOSE_FILE")" = "ABSENT" ] || fail "the table did not actually drop"

  step "restoring from the dump"
  gunzip -c "$DUMP" | ev exec -T postgres psql -U postgres -d pataspace -q >/dev/null 2>&1 || true

  if [ "$(read_marker "$EVAL_PROJECT" "$COMPOSE_FILE")" = "$MARKER" ]; then
    pass "dump restored the dropped table and its row ($(du -h "$DUMP" | awk '{print $1}'))"
  else
    fail "restore did not bring the marker row back"
  fi
else
  fail "pg_dump or gzip produced no usable backup"
fi

# =============================================================================
scenario "6. production volumes were never touched by this eval"
# =============================================================================
# The eval is the one thing here allowed to run destructive commands. Prove it
# stayed inside its namespace.
LEAKED=0
for prod_vol in pataspace_postgres_data pataspace_redis_data docker_postgres_data docker_redis_data; do
  if docker volume inspect "$prod_vol" >/dev/null 2>&1; then
    owner="$(docker volume inspect "$prod_vol" --format '{{index .Labels "com.docker.compose.project"}}' 2>/dev/null || true)"
    case "$owner" in
      "$EVAL_PROJECT"*) say "  $prod_vol is labelled with the eval project"; LEAKED=1 ;;
    esac
  fi
done
if [ "$LEAKED" = 0 ]; then
  pass "no production volume was created, mounted, or relabelled by this run"
else
  fail "the eval touched a production volume"
fi

# --- Verdict ------------------------------------------------------------------
say ""
say "----------------------------------------------------------------"
if [ "$FAILED" -eq 0 ]; then
  printf '%s  %d/%d scenarios passed — a rebuild cannot wipe the database.%s\n' \
    "$C_OK" "$PASSED" "$((PASSED+FAILED))" "$C_OFF" >&2
  exit 0
fi
printf '%s  %d/%d scenarios passed, %d FAILED — do not deploy.%s\n' \
  "$C_NO" "$PASSED" "$((PASSED+FAILED))" "$FAILED" "$C_OFF" >&2
exit 1
